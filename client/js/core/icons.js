/** Keeps `root` free of interface emoji as the page changes (batched once a frame). */
export function watchIcons(root = document.body) {
  iconize(root);
  const pending = new Set();
  let queued = false;
  const flush = () => { queued = false; for (const x of pending) if (x.isConnected) iconize(x); pending.clear(); };
  const mo = new MutationObserver(list => {
    for (const r of list) {
      if (r.type === 'characterData') pending.add(r.target);
      else if (r.type === 'attributes') convertAttrs(r.target);
      else for (const x of r.addedNodes) pending.add(x);
    }
    // converted right away (a microtask) so nothing is painted with its emoji first
    if (pending.size && !queued) { queued = true; queueMicrotask(flush); }
  });
  mo.observe(root, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: ['title', 'aria-label'] });
  return mo;
}

const paths = new Map();
/** Draws an icon on a canvas, centred on x, y, `size` px across, in `colour`. */
export function drawIcon(ctx, name, x, y, size, colour = '#fff') {
  const p = ICONS[name];
  if (!p) return false;
  let P = paths.get(name);
  if (!P) { P = [p[0] ? new Path2D(p[0]) : null, p[1] ? new Path2D(p[1]) : null]; paths.set(name, P); }
  ctx.save();
  ctx.translate(x - size / 2, y - size / 2); ctx.scale(size / 24, size / 24);
  ctx.strokeStyle = colour; ctx.fillStyle = colour; ctx.lineWidth = 1.9; ctx.lineCap = 'round'; ctx.lineJoin = 'round';
  if (P[0]) ctx.stroke(P[0]);
  if (P[1]) ctx.fill(P[1]);
  ctx.restore();
  return true;
}
