const n = v => Math.round(v * 100) / 100;
/** A circle as a path (so every icon is paths only: the same data draws in SVG and on a canvas). */
const C = (x, y, r) => `M${n(x - r)} ${n(y)}a${n(r)} ${n(r)} 0 1 0 ${n(2 * r)} 0a${n(r)} ${n(r)} 0 1 0 ${n(-2 * r)} 0`;
/** A rectangle, corners rounded r. */
const R = (x, y, w, h, r = 0) => r
  ? `M${n(x + r)} ${n(y)}h${n(w - 2 * r)}a${r} ${r} 0 0 1 ${r} ${r}v${n(h - 2 * r)}a${r} ${r} 0 0 1 ${-r} ${r}h${n(-(w - 2 * r))}a${r} ${r} 0 0 1 ${-r} ${-r}v${n(-(h - 2 * r))}a${r} ${r} 0 0 1 ${r} ${-r}z`
  : `M${n(x)} ${n(y)}h${n(w)}v${n(h)}h${n(-w)}z`;
const rad = d => d * Math.PI / 180;
const pt = (cx, cy, r, a) => [cx + r * Math.cos(rad(a)), cy + r * Math.sin(rad(a))];   // degrees, clockwise (y down)
/** An arc from angle a0 to a1 (degrees, clockwise positive; a1 < a0 runs anticlockwise). */
function A(cx, cy, r, a0, a1) {
  const [x0, y0] = pt(cx, cy, r, a0), [x1, y1] = pt(cx, cy, r, a1);
  return `M${n(x0)} ${n(y0)}A${r} ${r} 0 ${Math.abs(a1 - a0) > 180 ? 1 : 0} ${a1 > a0 ? 1 : 0} ${n(x1)} ${n(y1)}`;
}
/** An arrowhead (a chevron) at x, y pointing along angle `dir` (degrees). */
const head = (x, y, dir, len = 3.6, spread = 42) => {
  const [ax, ay] = pt(x, y, len, dir + 180 - spread), [bx, by] = pt(x, y, len, dir + 180 + spread);
  return `M${n(ax)} ${n(ay)}L${n(x)} ${n(y)}L${n(bx)} ${n(by)}`;
};
/** An arc with an arrowhead where it ends. */
const arcArrow = (cx, cy, r, a0, a1) => { const [x, y] = pt(cx, cy, r, a1); return A(cx, cy, r, a0, a1) + head(x, y, a1 + (a1 > a0 ? 90 : -90)); };
/** A straight arrow from (x0, y0) to (x1, y1). */
const arrow = (x0, y0, x1, y1) => `M${x0} ${y0}L${x1} ${y1}` + head(x1, y1, Math.atan2(y1 - y0, x1 - x0) * 180 / Math.PI);
/** A star of `k` points (outer r, inner ri). */
function star(cx, cy, r, ri, k = 5, rot = -90) {
  let d = '';
  for (let i = 0; i < k * 2; i++) { const [x, y] = pt(cx, cy, i % 2 ? ri : r, rot + i * 180 / k); d += (i ? 'L' : 'M') + n(x) + ' ' + n(y); }
  return d + 'z';
}
/** Rays round a centre. */
const rays = (cx, cy, r0, r1, k, rot = 0) => Array.from({ length: k }, (_, i) => { const a = rot + i * 360 / k, [x0, y0] = pt(cx, cy, r0, a), [x1, y1] = pt(cx, cy, r1, a); return `M${n(x0)} ${n(y0)}L${n(x1)} ${n(y1)}`; }).join('');
/** A gear: teeth round a ring, a hole in the middle. */
function gear(cx, cy, ro, ri, k) {
  let d = '';
  const step = 360 / k;
  for (let i = 0; i < k; i++) {
    const a = i * step - 90;
    for (const [r, o] of [[ri, -step * 0.5], [ri, -step * 0.28], [ro, -step * 0.17], [ro, step * 0.17], [ri, step * 0.28]]) {
      const [x, y] = pt(cx, cy, r, a + o); d += (d ? 'L' : 'M') + n(x) + ' ' + n(y);
    }
  }
  return d + 'z' + C(cx, cy, ro * 0.36);
}
/** A rounded triangle (warning). */
function triangle(cx, top, w, h, r) {
  const P = [[cx, top], [cx + w / 2, top + h], [cx - w / 2, top + h]];
  let d = '';
  for (let i = 0; i < 3; i++) {
    const [px, py] = P[(i + 2) % 3], [x, y] = P[i], [nx, ny] = P[(i + 1) % 3];
    const l1 = Math.hypot(px - x, py - y), l2 = Math.hypot(nx - x, ny - y);
    d += `${i ? 'L' : 'M'}${n(x + (px - x) * r / l1)} ${n(y + (py - y) * r / l1)}Q${n(x)} ${n(y)} ${n(x + (nx - x) * r / l2)} ${n(y + (ny - y) * r / l2)}`;
  }
  return d + 'z';
}
