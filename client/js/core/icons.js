const TONES = { good: 1, bad: 1, gold: 1, dim: 1 };
/** SVG markup for an icon (empty for an unknown name). */
export function icon(name, tone = '', emoji = '') {
  const p = ICONS[name];
  if (!p) return '';
  const t = TONES[tone] ? ` t-${tone}` : '';
  return `<svg class="mvi${t}" viewBox="0 0 24 24" aria-hidden="true" focusable="false">${emoji ? `<desc>${emoji}</desc>` : ''}`
    + `${p[0] ? `<path d="${p[0]}"/>` : ''}${p[1] ? `<path class="f" d="${p[1]}"/>` : ''}</svg>`;
}
const lookup = e => { const v = EMOJI[e.replace(/️/g, '')]; return v ? (Array.isArray(v) ? v : [v, '']) : null; };
/** The icon for an emoji (or ''), for code that holds emoji in data (the world map). */
export const iconFor = e => { const v = lookup(e); return v ? v[0] : ''; };

// Mapped emoji (and their variation selector) in text.
const RE = new RegExp('(' + Object.keys(EMOJI).sort((a, b) => b.length - a.length).map(e => e.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|') + ')️?', 'g');
const SKIP = new Set(['SCRIPT', 'STYLE', 'TEXTAREA', 'INPUT', 'NOSCRIPT', 'CODE', 'PRE']);
const NO_ICON = '[data-noicon], .bubble, .ac-b, .pc-l, [contenteditable="true"]';   // people's own words
// Agents' and residents' own emoji: kept as emoji unless the person chose the theme's style (the browser's copy is read at
// once, so a page never shows them in the wrong style first; the account's choice arrives with its preferences).
let avatarStyle = 'normal';
try { if (typeof localStorage !== 'undefined' && localStorage.getItem('mvw.agentEmoji') === 'styled') avatarStyle = 'styled'; } catch { /* private mode */ }
const parser = typeof document !== 'undefined' ? document.createElement('template') : null;

function convertText(t) {
  const s = t.nodeValue;
  RE.lastIndex = 0;
  if (!RE.test(s)) return;
  const el = t.parentElement;
  if (!el || SKIP.has(el.tagName) || el.closest('svg') || el.closest(NO_ICON)) return;
  if (avatarStyle !== 'styled' && el.closest('[data-avatar]')) return;
  if (el.tagName === 'OPTION' || el.closest('select')) {   // an option can't hold a picture: drop the emoji from its label
    const v = s.replace(RE, '').replace(/^\s+/, '');
    if (v !== s) t.nodeValue = v;
    return;
  }
  RE.lastIndex = 0;
  let html = '', last = 0, m;
  const esc = x => x.replace(/&/g, '&amp;').replace(/</g, '&lt;');
  while ((m = RE.exec(s))) {
    const [name, tone] = lookup(m[1]);
    html += esc(s.slice(last, m.index)) + icon(name, tone, m[0]);
    last = m.index + m[0].length;
  }
  html += esc(s.slice(last));
  parser.innerHTML = html;
  t.replaceWith(parser.content);
}
function convertAttrs(el) {
  for (const a of ['title', 'aria-label']) {
    const v = el.getAttribute && el.getAttribute(a);
    if (!v) continue;
    RE.lastIndex = 0;
    if (RE.test(v)) el.setAttribute(a, v.replace(RE, '').replace(/^\s+/, '').trim());
  }
}
/** Replaces the mapped emoji under `node` with icons. */
export function iconize(node) {
  if (!node) return;
  if (node.nodeType === 3) return convertText(node);
  if (node.nodeType !== 1 && node.nodeType !== 11) return;
  if (node.nodeType === 1) { if (SKIP.has(node.tagName) || node.namespaceURI === 'http://www.w3.org/2000/svg') return; convertAttrs(node); }
  const texts = [];
  const w = document.createTreeWalker(node, 5 /* elements and text */, {
    acceptNode: x => x.nodeType === 1 ? (SKIP.has(x.tagName) || x.namespaceURI === 'http://www.w3.org/2000/svg' ? 2 : (convertAttrs(x), 3)) : 1,
  });
  for (let x = w.nextNode(); x; x = w.nextNode()) if (x.nodeType === 3) texts.push(x);
  for (const t of texts) convertText(t);
}
/** Agents' and residents' own emoji as emoji ('normal') or in the theme's style ('styled'), now and from here on. */
export function setAvatarStyle(mode, root = typeof document !== 'undefined' ? document.body : null) {
  avatarStyle = mode === 'styled' ? 'styled' : 'normal';
  if (!root) return avatarStyle;
  for (const el of root.querySelectorAll('[data-avatar]')) {
    if (avatarStyle === 'styled') iconize(el);
    else for (const s of el.querySelectorAll('svg.mvi')) s.replaceWith(s.querySelector('desc')?.textContent || '');   // back to the emoji it replaced
  }
  return avatarStyle;
}
