// Triangles and file size of every dressing copy (client/assets/{gso,abo}/d/*.glb, the light models the dressing draws:
// shared/dress.js) -> shared/goods-tris.js, so a floor's dressing keeps to its budgets before any model has loaded
// (PLAN-SURFACES.md 9). Reads only each file's JSON chunk (index counts), no decoding. Run from the repository's folder: node tools/goods-tris.mjs
import fs from 'node:fs';
import { CATALOG } from '../shared/catalog.js';
import { goodsFiles, ABO_DRESS } from '../shared/goods-items.js';

function tris(file) {
  const b = fs.readFileSync(file), n = b.readUInt32LE(12), J = JSON.parse(b.subarray(20, 20 + n).toString('utf8'));
  let t = 0;
  for (const m of J.meshes || []) for (const p of m.primitives || []) t += p.indices !== undefined ? J.accessors[p.indices].count / 3 : (J.accessors[p.attributes.POSITION].count / 3);
  return [Math.round(t), b.length];
}
const out = [], miss = [];
for (const [t, d] of Object.entries(CATALOG)) {
  let f = null;
  if (d.goods) f = goodsFiles(t).d;
  else if (d.abo && d.onOk && ABO_DRESS.has(d.abo)) f = `/assets/abo/d/${d.abo}.glb`;
  if (!f) continue;
  const p = new URL('../client' + f, import.meta.url);
  if (!fs.existsSync(p)) { miss.push(t); continue; }
  const [n, bytes] = tris(p);
  out.push(`${t}:${n}:${Math.round(bytes / 1024)}`);
}
fs.writeFileSync(new URL('../shared/goods-tris.js', import.meta.url), `// My Virtual World — generated by tools/goods-tris.mjs (do not edit by hand): triangles and KB of each dressing copy,\n// type:triangles:KB, one per model the dressing may draw (shared/dress.js budgets).\nexport const GOODS_TRIS = \`\n${out.join('\n')}\n\`;\n`);
console.log('models', out.length, 'missing', miss.length, miss.slice(0, 5).join(' '));
